const DICT: Record<Lang, Record<string, string>> = { vi: VI, en: EN };

/** Dịch 1 khóa theo ngôn ngữ đang chọn (không hook — dùng ngoài component). */
export function translate(key: string, l: Lang = lang): string {
  return DICT[l][key] ?? DICT.vi[key] ?? key;
}

/** Hook dịch: tự re-render khi người dùng đổi ngôn ngữ. */
export function useT(): (key: string) => string {
  const l = useLang();
  return (key: string) => translate(key, l);
}
