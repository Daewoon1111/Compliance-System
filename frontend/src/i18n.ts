const DICT: Record<Lang, Record<string, string>> = { vi: VI, en: EN };

/** Dịch 1 khóa theo ngôn ngữ đang chọn (không hook — dùng ngoài component). */
export function translate(key: string, l: Lang = lang): string {
  return DICT[l][key] ?? DICT.vi[key] ?? key;
}

/** Hook dịch: tự re-render khi người dùng đổi ngôn ngữ. */
export function useT(): (key: string) => string {
  const l = useLang();
  return (key: string) => translate(key, l);
}

/**
 * NHÃN DANH MỤC SONG NGỮ — khu vực · quốc gia · loại hình lao động.
 *
 * `markets.json` khai mỗi mục theo đúng MỘT quy ước, ghi rõ trong `note` của chính
 * file đó: `"English (Tiếng Việt)"`. Đây KHÔNG phải nội dung nghiệp vụ do backend
 * suy luận (thứ mà i18n cố ý không dịch) mà là một cặp nhãn đã có sẵn cả hai bản —
 * việc còn lại chỉ là chọn đúng bản, thay vì bắt người dùng đọc cả hai trong một
 * dòng như trước.
 *
 * Tách ở FRONTEND chứ không ở API: đổi ngôn ngữ khi đó không phải gọi lại
 * `/markets`, và danh sách đang mở không bị nháy.
 *
 * Không khớp quy ước (mục do người dùng tự thêm ở trang quản trị) -> trả nguyên văn:
 * thà hiện một nhãn chưa song ngữ còn hơn cắt nhầm mất một nửa tên.
 */
/** Tách cặp `"English (Tiếng Việt)"` tại cặp ngoặc CUỐI cùng, đếm theo ĐỘ SÂU.
 *
 *  Không dùng regex được: 6/76 mục có ngoặc LỒNG trong chính phần tên
 *  (`"Seafaring work (international routes) (Công việc trên biển (tàu tuyến quốc tế))"`,
 *  `"Technical intern trainee (Thực tập sinh kỹ năng (TTS))"`). Regex `(.+?)\((.*)\)`
 *  lười ở vế đầu nên cắt ngay ngoặc THỨ NHẤT: bản tiếng Việt lãnh trọn phần đuôi tiếng
 *  Anh còn lại, hiện ra thành `"international routes) (Công việc trên biển (tàu tuyến quốc tế)"`.
 *  Quét ngược từ ')' cuối và đếm độ sâu thì lấy đúng vế trong cùng cấp. */
function splitBilingual(name: string): { en: string; vi: string } | null {
  const s = String(name ?? "").trim();
  if (!s.endsWith(")")) return null;
  let depth = 0;
  for (let i = s.length - 1; i >= 0; i--) {
    if (s[i] === ")") depth++;
    else if (s[i] === "(" && --depth === 0) {
      const en = s.slice(0, i).trim();
      const vi = s.slice(i + 1, -1).trim();
      return en && vi ? { en, vi } : null;
    }
  }
  return null;
}

export function catLabel(name: string, l: Lang = lang): string {
  const pair = splitBilingual(name);
  return pair ? (l === "en" ? pair.en : pair.vi) : String(name ?? "");
}

/** Hook bản song ngữ: tự re-render khi đổi ngôn ngữ.
 *  `useCallback` để hàm GIỮ NGUYÊN tham chiếu giữa các lần render — nó được dùng làm
 *  dependency của `useMemo` dựng danh sách quốc gia; hàm mới mỗi render sẽ khiến
 *  danh sách đó tính lại liên tục dù không có gì đổi. */
export function useCatLabel(): (name: string) => string {
  const l = useLang();
  return useCallback((name: string) => catLabel(name, l), [l]);
}
